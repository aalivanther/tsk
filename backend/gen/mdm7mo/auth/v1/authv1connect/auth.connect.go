// En español: define TODO el ciclo de vida de una cuenta: registrarse, iniciar sesión, consultar
// "quién soy", cerrar sesión, cambiar la contraseña, pedir un restablecimiento cuando se olvidó y
// borrar la cuenta por completo. El login es OPCIONAL en el producto: se puede explorar sin cuenta;
// la cuenta sirve para tener un perfil propio sincronizado entre dispositivos.
//
// Cómo funcionan las sesiones (cambió en la Fase BETA): el servidor emite un token OPACO y aleatorio,
// guarda solo su huella en la base de datos y lo entrega por UN ÚNICO camino — la cookie
// `tsk_session`, marcada de forma que el JavaScript de la página no puede leerla ni escribirla.
//
// Dos decisiones que conviene entender juntas:
//
//   1. La sesión EXISTE en el servidor, así que se puede REVOCAR de verdad. Cerrar sesión, cambiar la
//      contraseña o borrar la cuenta invalidan los accesos abiertos en el acto. Con el esquema
//      anterior —un token firmado que el servidor no guardaba— eso era sencillamente imposible: una
//      credencial robada valía treinta días aunque su dueño "cerrara sesión".
//
//   2. El token NO viaja además en el cuerpo de la respuesta. Lo hizo durante un tiempo, para que el
//      frontend pudiera guardarlo y reenviarlo, y eso obligaba a tenerlo en un sitio que cualquier
//      script de la página podía leer. Desde que el navegador llama al backend a través de la propia
//      dirección de la web, la cookie llega sola y ese rodeo sobra. Un segundo camino que ya nadie usa
//      no es compatibilidad: es una puerta más que vigilar.

