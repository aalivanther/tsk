// si el servidor ya va por otra más nueva, RECHAZA el guardado con FailedPrecondition y devuelve —en
// el detalle del error— el documento que él tiene, para que el cliente fusione y reintente. Sin esto,
// la última escritura ganaría a ciegas y borraría en silencio lo que hizo el otro dispositivo.

